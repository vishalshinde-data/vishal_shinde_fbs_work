#Pattern: A pattern is a repeated of regular arrangement of things.

# star
for i in range(1, 6):
    for j in range(1, 8):
        print('*', end = ' ')
    print()

#doller
for i in range(1, 6):
    for j in range(1, 6):
        print('$', end = ' ')
    print() 

       
#numbers
for i in range(1, 6):
    for j in range(1, 6):
        print(i, end = ' ')
    print()

for i in range(1, 6):
    for j in range(1, 6):
        print(j, end = ' ')
    print()        
    